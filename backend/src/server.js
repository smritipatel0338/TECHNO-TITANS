import 'dotenv/config';
import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import morgan from 'morgan';
import rateLimit from 'express-rate-limit';
import { connectDB } from './config/db.js';
import authRoutes from './routes/auth.js';
import habitRoutes from './routes/habits.js';
import friendRoutes from './routes/friends.js';
import simulationRoutes from './routes/simulations.js';
const app = express();
app.use(helmet()); app.use(cors({ origin: process.env.CLIENT_ORIGIN?.split(',') || 'http://localhost:5173' }));
app.use(express.json({ limit: '100kb' })); app.use(morgan('dev'));
app.use('/api', rateLimit({ windowMs: 15 * 60 * 1000, limit: 300, standardHeaders: 'draft-7', legacyHeaders: false }));
app.get('/api/health', (_req,res)=>res.json({ status:'ok', service:'future-you-api' }));
app.use('/api/auth', authRoutes); app.use('/api/habits', habitRoutes); app.use('/api/friends', friendRoutes); app.use('/api/simulations', simulationRoutes);
app.use((err, _req, res, _next) => { console.error(err); if (err.code === 11000) return res.status(409).json({ message: 'That record already exists.' }); if (err.name === 'ValidationError') return res.status(400).json({ message: err.message }); res.status(500).json({ message: 'Something went wrong. Please try again.' }); });
const port = process.env.PORT || 5000;
connectDB().then(()=>app.listen(port, ()=>console.log(`Future You API running on ${port}`))).catch(err=>{ console.error(err.message); process.exit(1); });
